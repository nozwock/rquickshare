// Probe: advertise a QuickShare *receiver* endpoint over 0xFEF3, cloned byte-for-byte
// from Martin's Pixel 9 Pro capture, but with endpoint_id "PKT1" and name
// "Packet Linux Test 01" (same 20-byte length so all length fields stay valid).
// Goal: find out whether an off-WiFi sending Pixel will list a non-Android device.
use std::collections::BTreeMap;

use bluer::adv::{Advertisement, Type};
use bluer::{Uuid, UuidExt};

// 132-byte 0xFEF3 service data. Derived from the live capture; only the 4-byte
// endpoint_id (offset 12) and the 20-byte device name (offset 35) were substituted.
const SERVICE_DATA: [u8; 132] = [
    0x48, 0xfc, 0x9f, 0x5e, 0x00, 0x00, 0x00, 0x37, 0x23, 0xfc, 0x9f, 0x5e, 0x50, 0x4b, 0x54, 0x31,
    0x26, 0x22, 0x4a, 0x22, 0x71, 0x16, 0x9c, 0x15, 0x99, 0xa2, 0x44, 0xaf, 0x44, 0xb0, 0x17, 0x9c,
    0x0f, 0x23, 0x14, 0x50, 0x61, 0x63, 0x6b, 0x65, 0x74, 0x20, 0x4c, 0x69, 0x6e, 0x75, 0x78, 0x20,
    0x54, 0x65, 0x73, 0x74, 0x20, 0x30, 0x31, 0xfc, 0x41, 0x16, 0xb6, 0x17, 0x20, 0x00, 0x00, 0x62,
    0xf1, 0x03, 0x00, 0x82, 0x3f, 0xa0, 0x17, 0xfd, 0xf1, 0x70, 0x59, 0x6e, 0x1e, 0xd3, 0x4d, 0xe0,
    0x92, 0x56, 0x4d, 0x66, 0xd4, 0x29, 0x0f, 0x0f, 0x8f, 0x15, 0x05, 0x34, 0x7b, 0x13, 0x23, 0x01,
    0xea, 0x7f, 0x92, 0xa8, 0xd8, 0xd4, 0x61, 0x84, 0x15, 0x05, 0x3f, 0x00, 0x00, 0x84, 0x15, 0x06,
    0x2d, 0x00, 0x00, 0x84, 0x15, 0x04, 0x7f, 0x1f, 0x00, 0x84, 0x15, 0x07, 0x2d, 0x1f, 0x00, 0x83,
    0x15, 0x01, 0x15, 0x7c,
];

#[tokio::main(flavor = "current_thread")]
async fn main() -> Result<(), Box<dyn std::error::Error>> {
    let session = bluer::Session::new().await?;
    let adapter = session.default_adapter().await?;
    adapter.set_powered(true).await?;
    println!(
        "adapter {} @ {}",
        adapter.name(),
        adapter.address().await?
    );

    let uuid = Uuid::from_u16(0xFEF3);
    let mut service_data: BTreeMap<Uuid, Vec<u8>> = BTreeMap::new();
    service_data.insert(uuid, SERVICE_DATA.to_vec());

    let adv = Advertisement {
        advertisement_type: Type::Peripheral, // connectable, like the phone
        service_data,
        discoverable: Some(true),
        ..Default::default()
    };

    println!(
        "Registering 0xFEF3 receiver advert: {} bytes service data, name='Packet Linux Test 01', endpoint=PKT1",
        SERVICE_DATA.len()
    );
    let handle = adapter.advertise(adv).await?;
    println!("ADVERTISING. Open Quick Share -> Send on the Pixel and look for 'Packet Linux Test 01'. Ctrl-C to stop.");

    tokio::signal::ctrl_c().await?;
    drop(handle);
    println!("stopped");
    Ok(())
}
